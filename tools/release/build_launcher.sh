#!/usr/bin/env bash
# Build the release launcher `Project Pyrrhus.exe` from installer/launcher/launcher.c with the MinGW-w64 gcc of the
# .#win shell (from Project Helghast tools/release/build_launcher.sh). Run it through the sandbox:
#   nix develop .#win --command tools/sandbox.sh -- tools/release/build_launcher.sh [OUTDIR] [--smoke] [--icons DIR]
# OUTDIR defaults to build/launcher. Deterministic: -Os -s, no PE timestamp. ~20 KB, GUI subsystem, Unicode entry.
# launcher.rc (icon + version strings from installer/VERSION) compiled with windres; the icon comes from --icons DIR (default
# installer/art, generated by tools/release/installer_art.py). Without kz2-launcher.ico there it builds without
# resources and says so (the release build must have it: assemble the payload only after installer_art.py).
# --smoke also lays out OUTDIR/smoke/ (the launcher, a stand-in pythonw.exe from smoke_fakepy.c, an empty launch.py)
# for the Proton smoke test (tools/proton-test.sh on OUTDIR/smoke/"Project Pyrrhus.exe"); the stand-in never ships.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/build/launcher"; SMOKE=0; ICONS="$ROOT/installer/art"
while (( $# )); do
  case "$1" in
    --smoke) SMOKE=1 ;;
    --icons) ICONS="$2"; shift ;;
    *) OUT="$1" ;;
  esac
  shift
done
CC="${CC:-x86_64-w64-mingw32-gcc}"
WINDRES="${WINDRES:-x86_64-w64-mingw32-windres}"
# shellcheck disable=SC2054  # the comma belongs to the -Wl option
FLAGS=(-Os -s -municode -mwindows -Wall -Wextra -Werror -Wl,--no-insert-timestamp)
mkdir -p "$OUT"
RES=()
if [[ -f "$ICONS/kz2-launcher.ico" ]]; then
  # The version block comes from installer/VERSION (release_version.py refuses anything but MAJOR.MINOR.PATCH)
  VER="$(python3 "$ROOT/tools/release/release_version.py" --check | sed -n 's/^ok //p')"
  [[ -n "$VER" ]] || { python3 "$ROOT/tools/release/release_version.py" --check; exit 1; }
  printf '#define KZ2_VER_COMMA %s\n#define KZ2_VER_STR "%s"\n' "$(python3 "$ROOT/tools/release/release_version.py" --rc)" "$VER" \
    > "$OUT/launcher_version.h"
  "$WINDRES" --include-dir "$ICONS" --include-dir "$OUT" -O coff -o "$OUT/launcher.res.o" "$ROOT/installer/launcher/launcher.rc"
  RES=("$OUT/launcher.res.o")
else
  echo "build_launcher: no $ICONS/kz2-launcher.ico: built WITHOUT icon and version resources (run installer_art.py)" >&2
fi
"$CC" "${FLAGS[@]}" -o "$OUT/Project Pyrrhus.exe" "$ROOT/installer/launcher/launcher.c" "${RES[@]}"
ls -l "$OUT/Project Pyrrhus.exe" | awk '{print $5, $NF}'
sha256sum "$OUT/Project Pyrrhus.exe" | cut -c1-64
if (( SMOKE )); then
  S="$OUT/smoke"
  rm -rf "$S"; mkdir -p "$S/toolchain/python" "$S/kz2-setup/release"
  cp "$OUT/Project Pyrrhus.exe" "$S/"
  "$CC" "${FLAGS[@]}" -o "$S/toolchain/python/pythonw.exe" "$ROOT/installer/launcher/smoke_fakepy.c"
  : > "$S/kz2-setup/release/launch.py"
  echo "smoke tree: $S"
fi

def esc(s):
    return html.escape(s, quote=True)


def pub(root, rel):
    """A public/ path in either layout: the public repository has public/'s files at its root (no public/ folder)."""
    root = pathlib.Path(root)
    if rel.startswith("public/") and not (root / "public").is_dir():
        return root / rel[len("public/"):]
    return root / rel


def ver_span(text):
    """One-line marker span that bump_version.py fills (every X.Y.Z inside becomes the new version)."""
    return "<!-- version -->" + text + "<!-- /version -->"


def read_rows(root, problems):
    """Rows of docs/features.tsv as dicts; '#' lines are skipped."""
    p = root / DATA
    if not p.exists():
        problems.append(f"{DATA} missing")
        return []
    with open(p, encoding="utf-8", newline="") as f:
        lines = [l for l in f if not l.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    for r in rows:
        if r.get("status") not in ORDER:
            problems.append(f"{DATA}: row '{r.get('feature')}' has status '{r.get('status')}'")
    return rows


def inline(text, base=""):
    """A cell of Markdown text -> HTML: links (relative ones point at the repository on GitHub, from the folder
    `base`), `code`, **bold**; decision references like (D40) or 'D2: ' are dropped as the export drops them."""
    text = re.sub(r"\s*\(D\d{1,2}(?:,\s*D\d{1,2})*\)|\bD\d{1,2}: ?", "", text)
    out = []
    pos = 0
    for m in re.finditer(r"\[([^\]]+)\]\(([^)\s]+)\)", text):
        out.append(esc(text[pos:m.start()]))
        url = m.group(2)
        if not re.match(r"(https?:|mailto:|#)", url):
            url = f"{REPO}/blob/main/{base}{url.lstrip('./')}"
        out.append(f'<a href="{esc(url)}">{esc(m.group(1))}</a>')
        pos = m.end()
    out.append(esc(text[pos:]))
    s = "".join(out)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    return re.sub(r"(?<![\w*])\*([^*]+)\*(?![\w*])", r"<em>\1</em>", s)


def req_tables(root, problems):
    """[(title, header, rows)] from the requirements page's tables named in REQ_TABLES."""
    p = root / REQ
    if not p.exists():
        problems.append(f"{REQ} missing")
        return []
    text = p.read_text(encoding="utf-8")
    out = []
    for section, cols, title in REQ_TABLES:
        m = re.search(r"^## " + re.escape(section) + r"[ \t]*$(.*?)(?=^## |\Z)", text, re.M | re.S)
        if not m:
            problems.append(f"{REQ}: section '{section}' not found")
            continue
        lines = [l for l in m.group(1).splitlines() if l.startswith("|")]
        if len(lines) < 3:
            problems.append(f"{REQ}: section '{section}' has no table")
            continue
        split = lambda l: [c.strip() for c in l.strip().strip("|").split("|")]  # noqa: E731
        head = split(lines[0])
        try:
            idx = [head.index(c) for c in cols]
        except ValueError:
            problems.append(f"{REQ}: table in '{section}' lacks one of the columns {cols}")
            continue
        rows = [[split(l)[i] for i in idx] for l in lines[2:] if len(split(l)) == len(head)]
        out.append((title, [head[i] for i in idx], rows))
    return out


HEADING = re.compile(r"## \[([^\]]+)\](?:[ \t]+-[ \t]+(\d{4}-\d\d-\d\d))?[ \t]*(?:\(([^)]*)\))?[ \t]*$")


def entries(root):
    """The whole CHANGELOG, in file order (newest first): [{version, date, note, released, items: [(section, text)],
    text}] for every '## [X] - DATE (note)' heading; '## [Unreleased]' has date None. Read whole on purpose: the page
    picks the newest entries, and the tests check every entry, never only the first few. An entry counts as released
    when it is dated and its note is 'pre-release' or 'release' (bump_version.py writes '(pre-release)')."""
    p = pub(root, CHANGELOG)
    if not p.exists():
        return []
    out, cur, section = [], None, ""
    for line in p.read_text(encoding="utf-8").splitlines():
        m = HEADING.match(line)
        if m:
            note = (m.group(3) or "").strip()
            cur = {"version": m.group(1), "date": m.group(2), "note": note, "items": [], "text": [],
                   "released": bool(m.group(2)) and note in ("pre-release", "release")}
            out.append(cur)
            section = ""
        elif cur is None:
            continue
        elif line.startswith("### "):
            section = line[4:].strip()
        elif line.startswith("- "):
            cur["items"].append((section, line[2:].strip()))
        elif line.strip() and not line.startswith("#"):
            cur["text"].append(line.strip())
    for e in out:
        e["text"] = " ".join(e["text"])
    return out


def clip(text, n=120):
    return text if len(text) <= n else text[:n - 1].rsplit(" ", 1)[0].rstrip(",;:- ") + "..."


def changelog(root, n=CHANGELOG_N):
    """Newest-first [(YYYY-MM-DD, version, text)] from the dated CHANGELOG entries, at most n (n=None: all): each item,
    or the entry's paragraph when it has no items; text cut at about 120 characters; internal wording skipped."""
    out = []
    for e in entries(root):
        if not e["date"]:
            continue
        lines = [t for _, t in e["items"]] or ([e["text"]] if e["text"] else [])
        for t in lines:
            if t and not INTERNAL.search(t):
                out.append((e["date"], e["version"], clip(t)))
                if n is not None and len(out) == n:
                    return out
    return out


def release_of(root, version):
    """The CHANGELOG entry for version, or None."""
    return next((e for e in entries(root) if e["version"] == version), None)


def todo(rows, n=TODO_N):
    """The next PS3 features not done yet, in table order: [(feature, status)], 'not yet' first, then the started ones."""
    ps3 = [r for r in rows if r["kind"] == "ps3"]
    pick = ([r for r in ps3 if r["status"] == "not yet"] + [r for r in ps3 if r["status"] == "in progress"]
            + [r for r in ps3 if r["status"] == "partial"])
    return [(r["feature"], r["status"]) for r in pick[:n]]


def status_badge(s):
    return f'<span class="st st-{STATUS_CLASS[s]}">{esc(LABEL[s])}</span>'


def public_row(r):
    """Same filter as FEATURES.md (tools/export_public_transforms.py): no backlog rows, no Release area."""
    return "BACKLOG" not in r["note"] and r["area"] != "Release"


def table(rows, head3):
    o = ["<div class=\"tw\"><table>\n<thead><tr><th>Feature</th><th>" + esc(head3[0]) + "</th><th>"
         + esc(head3[1]) + "</th></tr></thead>\n<tbody>\n"]
    for r in rows:
        o.append(f"<tr><td>{esc(r['feature'])}</td><td>{inline(r['detail'])}</td><td>{status_badge(r['status'])}</td></tr>\n")
    o.append("</tbody></table></div>\n")
    return "".join(o)


def divider(label):
    return f"<p class=\"divider\" aria-hidden=\"true\"><span>{esc(label)}</span></p>\n"


def more(href, label="More"):
    return f"<p class=\"more\"><a href=\"{esc(href)}\">{esc(label)}<span aria-hidden=\"true\"> &gt;</span></a></p>\n"


def long_date(d):
    y, m, dd = d.split("-")
    return f"{int(dd)} {MONTHS[int(m) - 1]} {y}"


def shots_found(root, problems):
    """[(YYYY-MM-DD or '', src, title, caption)] newest first, from SHOTS and the public collection."""
    out = []
    for name, title, caption in SHOTS:
        hit = sorted(pub(root, SHOTS_DIR).glob(f"*_{name}.png"))
        if not hit:
            problems.append(f"screenshot '{name}' not in {SHOTS_DIR}/")
            continue
        fname = hit[-1].name
        day = re.match(r"(\d{4})(\d\d)(\d\d)_", fname)
        out.append(("-".join(day.groups()) if day else "", "../docs/screenshots/" + fname, title, caption))
    out.sort(key=lambda s: s[0], reverse=True)
    return out


def download_block(root, version, problems):
    """The version and download block: from installer/VERSION and its CHANGELOG entry."""
    e = release_of(root, version)
    if e is None:
        problems.append(f"{CHANGELOG} has no entry for installer/VERSION {version}")
    if e and e["released"]:
        tag_url = f"{REPO}/releases/tag/v{version}"
        link = ver_span(f"<a href=\"{tag_url}\">v{version}</a>")
        get = ver_span(f"<a class=\"btn\" href=\"{tag_url}\">Download v{version}</a>")
        return ("<div class=\"dl\">\n"
                f"<p class=\"ver\">{link} <span>pre-release</span></p>\n"
                f"<p class=\"small\">{esc(long_date(e['date']))} · partly playable · Windows x64</p>\n"
                f"<p class=\"btns\">{get}<a class=\"btn alt\" href=\"{REPO}/releases\">All releases</a></p>\n"
                "<p>The release page has the installer (recommended) and the portable zip, each with a .sha256 file, "
                "and SHA256SUMS: check your download against them.</p>\n</div>\n")
    return ("<div class=\"dl\">\n<p class=\"ver\">No release yet</p>\n"
            "<p>No installer has been published yet. When one is, it appears on the "
            f"<a href=\"{REPO}/releases\">releases page</a>; until then the port can be built from source.</p>\n</div>\n")



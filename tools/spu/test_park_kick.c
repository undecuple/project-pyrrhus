/* KZ2 host test (patch 7014): the coherency "kick" line. With a line marked in the coherency bitmap
 * (spu_coh_reserve with no context, as the GCM walker's park arm does) and named in g_spu_coh_kick_line, every writer
 * of that line must call g_spu_coh_kick_fn after its bytes have landed: a PPU scalar store (vm_write32 ->
 * VM_WRITE_COH), an SPU PUT, PUTLLUC and a successful PUTLLC; a lifted raw store (stvx, the lifter's own lowering) is
 * a known gap in this tree (reported; a hard check with VM_RAW_COHERENT, as in tools/spu/test_putllc_ppu.c).
 * A write to another line, or with the kick line cleared, must not call it. Built by tools/spu/test_park_kick.sh
 * against the patched tree (SKIP without it or without patch 7014). Scaffold from tools/spu/test_putllc_ppu.c. */
#include <pthread.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
static uint8_t g_guest_mem[1u << 20];
uint8_t* vm_base = g_guest_mem;
uint32_t ppu_vm_size = 0;
#include "spu_channels.c"
#include "ppu_memory.h"
#include "ppu_raw_stores.h" /* generated by test_putllc_ppu.sh from the patched tools/ppu_lifter.py */
struct tctx { uint64_t gpr[32]; uint8_t vr[32][16]; uint64_t xer; uint32_t cr; };
#include "ppu_raw_ops.h" /* op_stvx/op_stvlx/op_stvrx/op_dcbz/op_stwbrx: the lifter's own lowering (v1/r5, EA r3+r4) */

unsigned long long ps3_ms_now(void) { return 0; }
void ppu_resv_break_store(uint64_t ea) { (void)ea; }
void ps3_ww_report_inline(uint32_t a, uint64_t v, int w) { (void)a; (void)v; (void)w; }
uint32_t g_ww_lo = 0xFFFFFFFFu, g_ww_hi = 0;
int g_resv_store_active = 0;
uint32_t g_barrier_sync_watch = 0;
void (*g_spurs_kernel_hook)(uint32_t) = 0;
uint32_t g_ydkj_spurs_ctx_ea = 0, g_ydkj_real_spurs_ea = 0, g_ydkj_real_taskset_ea = 0, g_ydkj_real_taskid = 0;
void spurs_ef_set_from_spu(uint32_t ea, uint16_t bits) { (void)ea; (void)bits; }
void ydkj_wake_all_event_flags(void) {}
uint64_t spurs_pm_build_context(uint8_t* ls, uint32_t ts, uint32_t t, uint32_t a, uint32_t b)
{ (void)ls; (void)ts; (void)t; (void)a; (void)b; return 0; }
uint32_t g_spu_image_src_ea, g_spu_image_ls_start, g_spu_image_span;
void spu_thread_publish_ctx(uint32_t tid, void* ctx) { (void)tid; (void)ctx; }
__attribute__((weak)) int g_kz2_joblog = 0;
__attribute__((weak)) void kz2_joblog_entry(spu_context* c) { (void)c; }
__attribute__((weak)) void kz2_joblog_get(spu_context* c, uint32_t a, uint32_t b, uint32_t d) { (void)c; (void)a; (void)b; (void)d; }
__attribute__((weak)) void kz2_joblog_put(spu_context* c, uint32_t a, uint32_t b) { (void)c; (void)a; (void)b; }
/* the lift preamble's externs */
int vm_inline_ok = 1;
uint32_t ppu_hle_inject_base = 0;

static int g_pass, g_fail;
#define CHECK(cond, ...) do { if (cond) g_pass++; else { g_fail++; fprintf(stdout, "FAIL %d: ", __LINE__); \
    fprintf(stdout, __VA_ARGS__); fputc('\n', stdout); } } while (0)
#define K 0x00030000u      /* the kick line (the park word at +0x2C) */
#define LSA 0x1000u
static spu_context g_s;
static struct tctx g_t;
static void wrch(spu_context* c, uint32_t ch, uint32_t v) { spu_wrch(c, ch, spu_make_preferred_u32(v)); }
static void mfc(uint32_t ea, uint32_t size, uint32_t cmd)
{ wrch(&g_s, MFC_LSA, LSA); wrch(&g_s, MFC_EAH, 0); wrch(&g_s, MFC_EAL, ea); wrch(&g_s, MFC_Size, size); wrch(&g_s, MFC_TagID, 1);
  wrch(&g_s, MFC_Cmd, cmd); }
static uint32_t mem32(uint32_t ea)
{ const uint8_t* p = vm_base + ea; return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | p[3]; }
static void ls32w(uint32_t o, uint32_t v)
{ uint8_t* p = g_s.ls + LSA + o; p[0] = (uint8_t)(v >> 24); p[1] = (uint8_t)(v >> 16); p[2] = (uint8_t)(v >> 8); p[3] = (uint8_t)v; }
static int g_kicks; static uint32_t g_kline, g_kword;
static void kick(uint32_t line) { g_kicks++; g_kline = line; g_kword = mem32(K + 0x2C); }
static void arm(void) { spu_coh_reserve(NULL, K + 0x2C); g_spu_coh_kick_fn = kick; g_spu_coh_kick_line = K; g_kicks = 0; g_kword = 0; }

int main(void)
{
    spu_context_init(&g_s, 0); g_s.spu_id = 0;
    memset(vm_base + K, 0, 256);
    arm();
    vm_write32(K + 0x2C, 0x0000AAAAu);
    CHECK(g_kicks == 1 && g_kline == K && g_kword == 0x0000AAAAu, "PPU vm_write32: kicks=%d line=0x%X word seen 0x%08X", g_kicks, g_kline, g_kword);
    arm();
    memset(g_t.vr[1], 0, 16); g_t.vr[1][12] = 0xBB; g_t.vr[1][15] = 0x01; g_t.gpr[3] = K; g_t.gpr[4] = 0x20; op_stvx(&g_t);
    /* The lift's raw stores (stvx, stwbrx, dcbz, ...) skip the coherency bitmap in this tree (KZ2 patch 7005 is not
     * carried; tools/spu/test_putllc_ppu.sh reports the same gap): reported, a hard check only with VM_RAW_COHERENT. */
#ifdef VM_RAW_COHERENT
    CHECK(g_kicks >= 1 && g_kline == K && g_kword == 0xBB000001u, "PPU raw stvx: kicks=%d word seen 0x%08X", g_kicks, g_kword);
#else
    printf("known gap: PPU raw stvx to the kick line: kicks=%d (raw stores are not coherent in this tree)\n", g_kicks);
#endif
    arm();
    memset(g_s.ls + LSA, 0, 128); ls32w(0x0C, 0x20000123u);   /* PUT of 16 bytes at K+0x20: the word at +0x2C */
    mfc(K + 0x20, 16, MFC_PUT_CMD);
    CHECK(g_kicks >= 1 && g_kword == 0x20000123u && mem32(K + 0x2C) == 0x20000123u, "SPU PUT: kicks=%d word seen 0x%08X", g_kicks, g_kword);
    arm();
    memcpy(g_s.ls + LSA, vm_base + K, 128); ls32w(0x2C, 0x20000456u);
    mfc(K, 128, MFC_PUTLLUC_CMD);
    CHECK(g_kicks >= 1 && g_kword == 0x20000456u, "SPU PUTLLUC: kicks=%d word seen 0x%08X", g_kicks, g_kword);
    arm();
    mfc(K, 128, MFC_GETLLAR_CMD); ls32w(0x2C, 0x20000789u); mfc(K, 128, MFC_PUTLLC_CMD);
    CHECK(g_s.atomic_stat == 0 && g_kicks >= 1 && g_kword == 0x20000789u, "SPU PUTLLC: stat=%u kicks=%d word seen 0x%08X",
          (unsigned)g_s.atomic_stat, g_kicks, g_kword);
    arm();
    vm_write32(K + 0x80 + 0x2C, 1);   /* the next line, not marked */
    spu_coh_reserve(NULL, K + 0x100); vm_write32(K + 0x100, 2);   /* marked, not the kick line */
    CHECK(g_kicks == 0, "other lines: kicks=%d", g_kicks);
    arm(); g_spu_coh_kick_line = 0;
    vm_write32(K + 0x2C, 3);
    CHECK(g_kicks == 0, "kick line cleared: kicks=%d", g_kicks);
    printf("park kick: %d passed, %d failed\n", g_pass, g_fail);
    return g_fail ? 1 : 0;
}

static int g_pass, g_fail, g_known;
#define CHECK(cond, ...) do { if (cond) g_pass++; else { g_fail++; fprintf(stdout, "FAIL %d: ", __LINE__); \
    fprintf(stdout, __VA_ARGS__); fputc('\n', stdout); } } while (0)

#ifdef VM_RAW_COHERENT
#define STRICT 1
#else
#define STRICT 0
#endif
#define LINE 0x00020000u /* count word at +0x00, PPU's word at +0x40 */
#define LSA 0x1000u
static spu_context g_s;
static void wrch(spu_context* c, uint32_t ch, uint32_t v) { spu_wrch(c, ch, spu_make_preferred_u32(v)); }
static void atomic_cmd(spu_context* c, uint32_t cmd)
{ wrch(c, MFC_LSA, LSA); wrch(c, MFC_EAH, 0); wrch(c, MFC_EAL, LINE); wrch(c, MFC_Cmd, cmd); }
static uint32_t ls32(spu_context* c, uint32_t o)
{ const uint8_t* p = c->ls + LSA + o; return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | p[3]; }
static void ls32w(spu_context* c, uint32_t o, uint32_t v)
{ uint8_t* p = c->ls + LSA + o; p[0] = (uint8_t)(v >> 24); p[1] = (uint8_t)(v >> 16); p[2] = (uint8_t)(v >> 8); p[3] = (uint8_t)v; }
static uint32_t mem32(uint32_t ea)
{ const uint8_t* p = vm_base + ea; return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | p[3]; }

/* GETLLAR, `between` (the PPU's store), count-1 into LS, PUTLLC; returns the PUTLLC status (0 = success). */
static int dec_once(void (*between)(void))
{
    atomic_cmd(&g_s, MFC_GETLLAR_CMD);
    if (between) between();
    ls32w(&g_s, 0, ls32(&g_s, 0) - 1);
    atomic_cmd(&g_s, MFC_PUTLLC_CMD);
    return (int)g_s.atomic_stat;
}
static void reset(void)
{
    spu_context_init(&g_s, 0);
    g_s.spu_id = 0;
    memset(vm_base + LINE, 0, 128);
    vm_write32(LINE, 10);
}
static void st_other_changed(void) { vm_write32(LINE + 0x40, 0x1234); }
static void st_other_same(void) { vm_write32(LINE + 0x40, mem32(LINE + 0x40)); }
static void st_count_same(void) { vm_write32(LINE, mem32(LINE)); }
static struct tctx g_t;
static void raw_changed(void) { memset(g_t.vr[1], 0, 16); g_t.vr[1][2] = 0x12; g_t.vr[1][3] = 0x34; g_t.gpr[3] = LINE; g_t.gpr[4] = 0x40; op_stvx(&g_t); }
static void raw_same(void) { memcpy(g_t.vr[1], vm_base + LINE + 0x40, 16); g_t.gpr[3] = LINE; g_t.gpr[4] = 0x40; op_stvx(&g_t); }
static void stvlx_same(void) { memcpy(g_t.vr[1], vm_base + LINE + 0x44, 12); g_t.gpr[3] = LINE; g_t.gpr[4] = 0x44; op_stvlx(&g_t); }
static void stvrx_same(void) { memcpy(g_t.vr[1] + 12, vm_base + LINE + 0x40, 4); g_t.gpr[3] = LINE; g_t.gpr[4] = 0x44; op_stvrx(&g_t); }
static void stwbrx_same(void) { uint32_t w; memcpy(&w, vm_base + LINE + 0x40, 4); g_t.gpr[5] = w; g_t.gpr[3] = LINE; g_t.gpr[4] = 0x40; op_stwbrx(&g_t); }
static void dcbz_other_line(void) { g_t.gpr[3] = LINE + 0x80; g_t.gpr[4] = 0; op_dcbz(&g_t); }
static void dcbz_same(void) { g_t.gpr[3] = LINE; g_t.gpr[4] = 0; op_dcbz(&g_t); }


/* Stress: SPU decrements the count STRESS_N times (retrying failed PUTLLCs); the PPU increments its word STRESS_N
 * times. Both totals must survive. */
#define STRESS_N 200000
static volatile int g_mode; /* 0 scalar, 1 raw */
static void* ppu_thread(void* a)
{
    (void)a;
    for (uint32_t i = 1; i <= STRESS_N; i++) {
        if (g_mode == 0) vm_write32(LINE + 0x40, i);
        else { static struct tctx t; memset(t.vr[1], 0, 16); t.vr[1][0] = (uint8_t)(i >> 24); t.vr[1][1] = (uint8_t)(i >> 16);
               t.vr[1][2] = (uint8_t)(i >> 8); t.vr[1][3] = (uint8_t)i; t.gpr[3] = LINE; t.gpr[4] = 0x40; op_stvx(&t); }
    }
    return NULL;
}
static uint32_t g_ppu_seen_max;
static void* spu_thread(void* a)
{
    (void)a;
    for (int i = 0; i < STRESS_N; i++) {
        for (;;) {
            atomic_cmd(&g_s, MFC_GETLLAR_CMD);
            ls32w(&g_s, 0, ls32(&g_s, 0) - 1);
            atomic_cmd(&g_s, MFC_PUTLLC_CMD);
            if (g_s.atomic_stat == 0) break;
        }
    }
    return NULL;
}
static void stress(int mode, const char* what)
{
    reset();
    vm_write32(LINE, STRESS_N);
    atomic_cmd(&g_s, MFC_GETLLAR_CMD); /* mark the line reserved once, as the game's first GETLLAR does */
    g_mode = mode;
    /* the PPU's word must only ever grow; any SPU commit that wrote back a stale copy shows as a smaller value
     * after the PPU thread is done, or as a count that is not 0 */
    pthread_t p, s;
    pthread_create(&s, NULL, spu_thread, NULL);
    pthread_create(&p, NULL, ppu_thread, NULL);
    pthread_join(p, NULL);
    pthread_join(s, NULL);
    uint32_t cnt = mem32(LINE), ppu = mem32(LINE + 0x40);
    (void)g_ppu_seen_max;
    printf("stress %s: count %u (want 0), PPU word %u (want %u)\n", what, cnt, ppu, STRESS_N);
    if (mode == 0 || STRICT) CHECK(cnt == 0 && ppu == STRESS_N, "stress %s lost an update", what);
    else if (!(cnt == 0 && ppu == STRESS_N)) { g_known++; printf("KNOWN GAP: raw store lost or was lost\n"); }
}

int main(void)
{
    int rc;
    reset(); rc = dec_once(st_other_changed);
    CHECK(rc == 1 && mem32(LINE) == 10 && mem32(LINE + 0x40) == 0x1234, "1 scalar store (other word, new value): PUTLLC rc=%d count=%u", rc, mem32(LINE));
    reset(); rc = dec_once(st_other_same);
    CHECK(rc == 1 && mem32(LINE) == 10, "2 scalar store (other word, same value): PUTLLC rc=%d count=%u", rc, mem32(LINE));
    reset(); rc = dec_once(st_count_same);
    CHECK(rc == 1 && mem32(LINE) == 10, "3 scalar store (count word, same value): PUTLLC rc=%d count=%u", rc, mem32(LINE));
    reset(); rc = dec_once(NULL);
    CHECK(rc == 0 && mem32(LINE) == 9, "0 control (no store): PUTLLC rc=%d count=%u", rc, mem32(LINE));
    reset(); rc = dec_once(raw_changed);
    CHECK(rc == 1 && mem32(LINE) == 10 && mem32(LINE + 0x40) == 0x1234, "4 stvx (new value): PUTLLC rc=%d count=%u", rc, mem32(LINE));
    /* Same bytes written back: Cell fails the PUTLLC (the store cancels the reservation). Hard checks once the lift
     * makes raw stores coherent (KZ2 patch 7005, vm_raw_resv in the preamble); before that they are reported. */
    struct { const char* what; void (*f)(void); } same[] = {
        { "5 stvx (same bytes)", raw_same }, { "6 stvlx (same bytes)", stvlx_same }, { "7 stvrx (same bytes)", stvrx_same },
        { "8 stwbrx (same bytes)", stwbrx_same }, { "9 dcbz of the reserved line, count already 0", dcbz_same } };
    for (unsigned k = 0; k < sizeof same / sizeof same[0]; k++) {
        reset();
        if (k == 4) vm_write32(LINE, 0), memset(vm_base + LINE, 0, 128);
        rc = dec_once(same[k].f);
        if (STRICT) CHECK(rc == 1, "%s: PUTLLC rc=%d (Cell: 1)", same[k].what, rc);
        else if (rc != 1) { g_known++; printf("KNOWN GAP: %s: PUTLLC rc=%d (Cell: 1)\n", same[k].what, rc); }
    }
    reset(); rc = dec_once(dcbz_other_line);
    CHECK(rc == 0 && mem32(LINE) == 9, "10 dcbz of the next line: PUTLLC rc=%d count=%u (want 0, 9)", rc, mem32(LINE));
    stress(0, "scalar");
    stress(1, "raw");
    printf("test_putllc_ppu: pass=%d fail=%d known-gap=%d\n", g_pass, g_fail, g_known);
    return g_fail ? 1 : 0;
}

/* KZ2 host test: does an SPU PUTLLC fail when the PPU writes the reserved 128-byte line between the SPU's
 * GETLLAR and its PUTLLC? (tokisaki-port's level-start stall: a pending count that an SPU task decrements with
 * GETLLAR/PUTLLC on a line the PPU also writes with plain stores.) On Cell any store to the line by another unit
 * loses the reservation, so the PUTLLC fails even when the store leaves the bytes as they were.
 * PPU store paths of the lifted code:
 *   scalar  stb/sth/stw/std -> vm_write8..64 (ppu_loader.cpp) -> VM_WRITE_COH (ppu_memory.h); here through
 *           ppu_memory.h's inline vm_write32, the same macro;
 *   raw     stvx/stvebx..stvewx, stwbrx/sthbrx/stdbrx, stvlx/stvrx, dcbz -> the lift's own preamble (VM_RAW_ST,
 *           vm_raw_st16, ...), compiled in from the patched lifter by test_putllc_ppu.sh (ppu_raw_stores.h).
 * Cases: 1-3 scalar store between GETLLAR and PUTLLC (another word / the same value / the counted word); 0 control;
 * 4 stvx with new bytes; 5-9 stvx, stvlx, stvrx, stwbrx, dcbz leaving the bytes as they were; 10 dcbz of the next
 * line (must not cancel); stress: one SPU thread decrements a count with GETLLAR/PUTLLC retry loops while the PPU
 * thread increments its own word of the same line (stw, then stvx): no update of either side may be lost.
 * The raw stores are the lifter's own lowering (test_putllc_ppu.sh generates ppu_raw_ops.h with
 * PPULifter._translate_op), so the test follows what the lift emits.
 * Built by tools/spu/test_putllc_ppu.sh against work/ps3recomp-patched (SKIP without it). */

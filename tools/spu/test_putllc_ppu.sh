#!/usr/bin/env bash
# KZ2 host test: PUTLLC against PPU stores to the reserved line (tools/spu/test_putllc_ppu.c). The raw-store
# helpers are taken from the patched lifter's preamble (tools/ppu_lifter.py, VM_RAW_LD .. vm_raw_st16) and the raw
# store instructions from its own lowering (PPULifter._translate_op), so the test follows what the lift emits. With
# KZ2 patch 7005 in the tree (vm_raw_resv in the preamble) the same-bytes raw-store cases are hard checks. Needs work/ps3recomp-patched (SPU_TREE=DIR); SKIP without it.
#   nix develop --command tools/sandbox.sh -- tools/spu/test_putllc_ppu.sh
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"; O="$ROOT/work/spu"; mkdir -p "$O/putllc_ppu"
T="${SPU_TREE:-$ROOT/${KZ2_OUT:-work}/ps3recomp-patched}"
[[ -f "$T/runtime/spu/spu_channels.c" && -f "$T/tools/ppu_lifter.py" ]] || { echo "SKIP: no patched toolkit at $T"; exit 0; }
H="$O/putllc_ppu/ppu_raw_stores.h"
{ echo "/* generated by tools/spu/test_putllc_ppu.sh from $T/tools/ppu_lifter.py */"
  sed -n '/^#define VM_RAW_LD(T, ea)/,/VM_RAW_ST(uint64_t, ea + 8, hi); }/p' "$T/tools/ppu_lifter.py"; } > "$H"
grep -q "vm_raw_st16" "$H" || { echo "FAIL: vm_raw_st16 not found in the lifter preamble"; exit 1; }
# The raw stores as the lifter lowers them (stvx/stvlx/stvrx v1,r3,r4; dcbz r3,r4; stwbrx r5,r3,r4).
python3 -I - "$T/tools" > "$O/putllc_ppu/ppu_raw_ops.h" <<'PY' || { echo "FAIL: lifter lowering"; exit 1; }
import struct, sys
sys.path.insert(0, sys.argv[1])
from ppu_disasm import disassemble_bytes
import ppu_lifter
L = ppu_lifter.PPULifter()
def x(xo, s=1, a=3, b=4): return (31 << 26) | (s << 21) | (a << 16) | (b << 11) | (xo << 1)
for name, raw in [("stvx", x(231)), ("stvlx", x(647)), ("stvrx", x(679)), ("dcbz", x(1014, 0)), ("stwbrx", x(662, 5))]:
    i = disassemble_bytes(struct.pack(">I", raw), 0x10000)[0]
    assert i.mnemonic == name, (name, i.mnemonic)
    print(f"static void op_{name}(struct tctx* ctx) {{ {L._translate_op(i, None)} }}")
PY
strict=""; grep -q "vm_raw_resv" "$H" && strict="-DVM_RAW_COHERENT=1"
B="runtime/spu/spu_drain.c runtime/spu/spu_lockstep.c runtime/spu/spu_coherency.c runtime/spu/spu_workload.c runtime/spu/spurs_policy.c runtime/spu/spurs_job.c runtime/spu/spu_tsp_weak.c runtime/spu/spu_vm_pagemap.c runtime/spu/spurs_policy_blob_weak.c runtime/spu/spu_interp.c runtime/platform/win32_compat.c"
extra=""; [[ -f "$T/runtime/diag/kz3_wait_acct.c" ]] && extra="runtime/diag/kz3_wait_acct.c -I runtime/diag"
rm -f "$O/t_putllc_ppu"
(cd "$T" && gcc -std=gnu17 -O2 -w -pthread -DPS3RECOMP_LL_STRIPED=1 -I include -I runtime/spu -I runtime/ppu -I runtime/platform \
    $strict -I "$O/putllc_ppu" -o "$O/t_putllc_ppu" "$ROOT/tools/spu/test_putllc_ppu.c" $B $extra -lm 2>&1 | grep -m8 error)
[[ -x "$O/t_putllc_ppu" ]] || { echo "FAIL: build"; exit 1; }
out="$(timeout 300 "$O/t_putllc_ppu" 2>/dev/null)"; r=$?
echo "$out" | tail -12
[[ $r == 0 ]] && echo PASS || echo FAIL
exit $r
